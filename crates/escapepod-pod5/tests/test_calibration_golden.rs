//! Cross-language pin for ADC → pA calibration (rnabioco/escapepod-rs#501).
//!
//! `tests/fixtures/calibration_pa.tsv` holds `(offset, scale, adc, pA)` rows,
//! every float as its IEEE-754 bit pattern. This test holds
//! [`escapepod_pod5::calibrate_pa`] to it bit for bit; the Python binding is
//! held to the same file by `tests/python/test_calibration_parity.py`. Between
//! them, Rust and Python cannot drift apart without one of the two failing.
//!
//! Regenerate (only if the definition is *meant* to change):
//! `ESCAPEPOD_REGEN_CALIBRATION_GOLDEN=1 cargo nextest run -p escapepod-pod5 --test test_calibration_golden`

use escapepod_pod5::calibrate_pa;
use std::path::PathBuf;

fn golden_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/calibration_pa.tsv")
}

/// Calibrations: an awkward non-representable pair, a realistic RNA004-like
/// pair, and the identity.
const CALIBRATIONS: [(f32, f32); 3] = [(7.3, 0.183_452_1), (-243.0, 0.180_271_6), (0.0, 1.0)];

fn adc_samples() -> Vec<i16> {
    let mut v: Vec<i16> = vec![
        i16::MIN,
        i16::MIN + 1,
        -2048,
        -1,
        0,
        1,
        2047,
        i16::MAX - 1,
        i16::MAX,
    ];
    v.extend((0..256).map(|i| ((i * 2_654_435_761u64 as i64 % 65_536) - 32_768) as i16));
    v.extend((0..64).map(|i| (i * 37 % 4096 - 2048) as i16));
    v
}

fn render() -> String {
    let mut out = String::from(
        "# ADC -> pA calibration golden (rnabioco/escapepod-rs#501).\n\
         # Columns: offset_bits scale_bits adc pa_bits; floats are IEEE-754 f32 bit patterns.\n\
         # Generated by crates/escapepod-pod5/tests/test_calibration_golden.rs.\n",
    );
    for &(offset, scale) in &CALIBRATIONS {
        for adc in adc_samples() {
            let pa = calibrate_pa(adc, offset, scale);
            out.push_str(&format!(
                "0x{:08x}\t0x{:08x}\t{}\t0x{:08x}\n",
                offset.to_bits(),
                scale.to_bits(),
                adc,
                pa.to_bits()
            ));
        }
    }
    out
}

fn hex(s: &str) -> u32 {
    u32::from_str_radix(s.trim_start_matches("0x"), 16).expect("hex f32 bits")
}

#[test]
fn calibrate_pa_matches_golden_bits() {
    let path = golden_path();
    if escapepod_pod5::env::flag("ESCAPEPOD_REGEN_CALIBRATION_GOLDEN") {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, render()).unwrap();
    }
    let text = std::fs::read_to_string(&path).expect("golden fixture present");
    let mut rows = 0usize;
    let mut unfused_differs = 0usize;
    for line in text
        .lines()
        .filter(|l| !l.starts_with('#') && !l.is_empty())
    {
        let f: Vec<&str> = line.split('\t').collect();
        assert_eq!(f.len(), 4, "malformed row: {line}");
        let offset = f32::from_bits(hex(f[0]));
        let scale = f32::from_bits(hex(f[1]));
        let adc: i16 = f[2].parse().unwrap();
        let want = hex(f[3]);
        let got = calibrate_pa(adc, offset, scale).to_bits();
        assert_eq!(
            got, want,
            "adc {adc}, offset {offset}, scale {scale}: 0x{got:08x} vs golden 0x{want:08x}"
        );
        if ((f32::from(adc) + offset) * scale).to_bits() != want {
            unfused_differs += 1;
        }
        rows += 1;
    }
    assert_eq!(rows, CALIBRATIONS.len() * adc_samples().len(), "row count");
    // Without this the golden could not tell the fused form from the unfused.
    assert!(
        unfused_differs > 0,
        "golden cannot distinguish fused from unfused"
    );
}
